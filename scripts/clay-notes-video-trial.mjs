import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {NotebookStore,parseTranscript,videoIdentity} from '../src/clay-notes/core.mjs';

export function parseBrowserExport(text){
  if(typeof text!=='string'||text.length>1_000_000)throw new Error('Invalid or oversized browser transcript export');
  const id=/^Video ID:\s*([A-Za-z0-9_-]{11})\s*$/m.exec(text)?.[1];
  const language=/^Language:\s*(\S+)\s*$/m.exec(text)?.[1];
  if(!id||!language)throw new Error('Browser export needs video id and language headers');
  const rows=[];
  for(const line of text.split(/\r?\n/)){
    const match=/^\[(?:(\d+):)?(\d{1,2}):(\d{2})\]\s+(.+)$/.exec(line);
    if(match){if(Number(match[3])>=60||Number(match[2])>=60)throw new Error('Invalid export timestamp');rows.push({start:Number(match[1]||0)*3600+Number(match[2])*60+Number(match[3]),text:match[4]});}
  }
  return {id,language,autoGenerated:/^Captions:\s*auto-generated\s*$/m.test(text),segments:parseTranscript(rows)};
}
export async function importVideoTrial({url,title,channel,exportPath,store,directory}){
  const identity=videoIdentity(url);const raw=await readFile(exportPath,'utf8');const parsed=parseBrowserExport(raw);
  if(parsed.id!==identity.id)throw new Error('Export video id does not match requested video');
  const target=store || await new NotebookStore(directory).init();
  let note=await target.create({url:identity.url,title,channel});
  // Preserve any pre-existing source/revisions; the trial never generates or replaces AI content.
  let imported=false;
  if(!note.segments.length && !note.revisions.length){note=await target.transcript(identity.id,parsed.segments,`browser-export:${parsed.language}${parsed.autoGenerated?':automatic':''}`);imported=true;}
  return {id:identity.id,url:identity.url,title,channel,language:parsed.language,autoGenerated:parsed.autoGenerated,segments:parsed.segments.length,characters:parsed.segments.reduce((sum,s)=>sum+s.text.length,0),lastCaptionSeconds:parsed.segments.at(-1).start,exportSha256:createHash('sha256').update(raw).digest('hex'),normalizedSha256:createHash('sha256').update(JSON.stringify(parsed.segments)).digest('hex'),sourceMethod:'native-browser-transcript-export',imported,notebookState:note.state,summaryCalls:0,summaryStatus:'pending operator Apply, lane-test evidence and paid-call approval',installedExtensionCapture:'not tested'};
}
