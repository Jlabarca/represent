import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'file:///C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';

const root = resolve(fileURLToPath(new URL('../experiments/alegor-mvp/', import.meta.url)));
const shots = resolve(root, 'screenshots');
mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto('http://127.0.0.1:8874/', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: 'Where to resume' }).waitFor();
assert.match(await page.locator('#timeline-title').innerText(), /Represent timeline/);
assert.ok(await page.locator('.evidence-link').count() > 0, 'Expected clickable source citations');
const projectStateCard = page.locator('.card').filter({ hasText: 'Project state' });
const primaryClaims = await projectStateCard.locator('.claim:visible').allInnerTexts();
assert.ok(primaryClaims.length <= 5, `Project state should show a short first layer: ${primaryClaims.length}`);
assert.ok(primaryClaims.every((text) => !/^\s*\|\s*-{3,}/m.test(text) && !/^\s*\|\s*Decision\s*\|/m.test(text)), 'Markdown table scaffolding should not appear as project claims');
const primaryText = await page.locator('#brief').innerText();
assert.ok(!/\b[a-f\d]{64}\b/i.test(primaryText), 'Full content hashes belong behind detail controls');
await page.locator('.evidence-link').first().click();
assert.equal(await page.locator('#evidence-drawer').evaluate((el) => el.open), true);
assert.ok(await page.locator('.doc-line.highlight').count() > 0, 'Citation should jump to a highlighted captured line');
await page.screenshot({ path: resolve(shots, 'alegor-desktop.png'), fullPage: true });
await page.getByRole('button', { name: /switch color theme/i }).click();
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.screenshot({ path: resolve(shots, 'alegor-desktop-dark.png'), fullPage: true });
await page.reload({ waitUntil: 'networkidle' });
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark', 'Theme choice should persist across reload');
await page.route('**/api/projects/represent/brief?*', async (route) => {
  const response = await route.fetch();
  const payload = await response.json();
  payload.brief.rangeStatus = 'unavailable';
  payload.brief.rangeNote = 'Synthetic browser-check response: baseline is outside captured history.';
  await route.fulfill({ response, json: payload });
});
await page.reload({ waitUntil: 'networkidle' });
assert.match(await page.locator('.range-unavailable').first().innerText(), /Change range unavailable/);
assert.match(await page.locator('.range-unavailable').first().innerText(), /outside captured history/);
assert.doesNotMatch(await page.locator('#brief').innerText(), /No Git or worktree change is recorded since this checkpoint/);
await page.screenshot({ path: resolve(shots, 'alegor-range-unavailable.png'), fullPage: true });
await page.unroute('**/api/projects/represent/brief?*');
await page.selectOption('#project-select', 'plane-sync');
await page.getByText('No explicit open next step was found in the selected project documents.').waitFor();
await page.screenshot({ path: resolve(shots, 'alegor-plane-sync.png'), fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: resolve(shots, 'alegor-mobile.png'), fullPage: true });
const overflow = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }));
assert.ok(overflow.scroll <= overflow.client + 1, `Mobile horizontal overflow ${JSON.stringify(overflow)}`);
await page.keyboard.press('Tab');
const focused = await page.evaluate(() => document.activeElement?.tagName);
assert.ok(focused && focused !== 'BODY', 'Tab should focus an interactive control');
assert.deepEqual(errors, [], `Browser errors: ${errors.join('; ')}`);
const report = { schema: 'alegor.browser-check/v1', baseUrl: 'http://127.0.0.1:8874/', desktop: { viewport: '1440x1000', citationsOpenEvidenceLine: true, themeToggleWorks: true, themePersistsOnReload: true, unavailableRangeShowsReason: true, rangeTest: 'synthetic intercepted API response', projectStateFirstLayerClaims: primaryClaims.length, markdownTableScaffoldingHidden: true, fullHashesHiddenBehindDetails: true }, mobile: { viewport: '390x844', horizontalOverflow: overflow.scroll > overflow.client, keyboardCanFocusControl: true }, projectSwitchShowsUnknownWhenNoOpenTask: true, screenshots: ['screenshots/alegor-desktop.png', 'screenshots/alegor-desktop-dark.png', 'screenshots/alegor-range-unavailable.png', 'screenshots/alegor-plane-sync.png', 'screenshots/alegor-mobile.png'] };
writeFileSync(resolve(root, 'browser-check.json'), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report, null, 2));
await browser.close();
